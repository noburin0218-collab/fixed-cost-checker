#!/usr/bin/env bash
#
# switch-domain.sh
# ----------------
# 独自ドメインへの切り替えを一括で行うメンテナンススクリプト。
#
# 使い方:
#   ./tools/switch-domain.sh <domain>
#   例: ./tools/switch-domain.sh kakei-hokenshitsu.com
#
# やること:
#   1. ./CNAME に新ドメインを書き込む（GitHub Pages のカスタムドメイン設定用）
#   2. 主要ファイル内の旧URL（GitHub Pages のユーザー名+リポジトリパス）を
#      新ドメイン（ルート配信なのでパスなし）に一括置換する
#   3. qr.png を新URL向けに再生成する
#   4. npm test を実行し、失敗したら中断する
#   5. 成功したら次にやるべきDNS設定などを日本語で案内する
#
# 注意: このスクリプトは git commit / push は一切行いません。
#       変更内容を確認してから、自分でコミット・プッシュしてください。

set -euo pipefail

# ---------------------------------------------------------------------------
# 0. 定数
# ---------------------------------------------------------------------------

# 置き換え対象の旧URL文字列（ホスト名 + リポジトリパス）
OLD_HOST_PATH="noburin0218-collab.github.io/fixed-cost-checker"

# GitHub Pages 側のホスト名（www の CNAME 案内用）
GH_PAGES_HOST="noburin0218-collab.github.io"

# 置換対象ファイル一覧（存在するものだけ処理する）
TARGET_FILES=(
  "index.html"
  "README.md"
  "RESUME.md"
  "SETUP.md"
  "MARKETING.md"
  "MONETIZATION.md"
  "HOSTING_CLOUDFLARE.md"
  "note_article.md"
  "config.js"
  "script.js"
  "styles.css"
)

# ---------------------------------------------------------------------------
# 1. 引数チェック
# ---------------------------------------------------------------------------

usage() {
  cat <<'EOS'
使い方: ./tools/switch-domain.sh <ドメイン>
例:     ./tools/switch-domain.sh kakei-hokenshitsu.com

<ドメイン> には "example.com" のような、プロトコル(https://)や
末尾スラッシュを含まない、裸のドメイン名を指定してください。
EOS
}

DOMAIN="${1:-}"

if [[ -z "${DOMAIN}" ]]; then
  echo "エラー: ドメインを指定してください。" >&2
  usage >&2
  exit 1
fi

if ! [[ "${DOMAIN}" =~ ^[a-z0-9.-]+\.[a-z]{2,}$ ]]; then
  echo "エラー: '${DOMAIN}' は有効なドメイン名の形式ではありません。" >&2
  usage >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# 2. リポジトリルートで実行されているか確認
# ---------------------------------------------------------------------------

if [[ ! -f "./index.html" ]]; then
  echo "エラー: リポジトリのルートディレクトリ（./index.html が存在する場所）で実行してください。" >&2
  exit 1
fi

echo "==> ドメインを '${DOMAIN}' に切り替えます..."

# ---------------------------------------------------------------------------
# 3. ./CNAME を書き込む（GitHub Pages のカスタムドメイン設定ファイル）
#    余計な改行やスラッシュを含めず、ちょうど1行だけ書き込む
# ---------------------------------------------------------------------------

printf '%s\n' "${DOMAIN}" > ./CNAME
echo "==> ./CNAME を更新しました: $(cat ./CNAME)"

# ---------------------------------------------------------------------------
# 4. 対象ファイル内の旧URL文字列を新ドメインに一括置換
#    （カスタムドメインはルート配信のため /fixed-cost-checker のパスは消える）
# ---------------------------------------------------------------------------

for f in "${TARGET_FILES[@]}"; do
  if [[ -f "${f}" ]]; then
    sed -i "s#${OLD_HOST_PATH}#${DOMAIN}#g" "${f}"
    echo "==> 置換しました: ${f}"
  fi
done

# ---------------------------------------------------------------------------
# 5. qr.png を新URL向けに再生成する（segno を使用、既存の見た目に合わせる）
# ---------------------------------------------------------------------------

NEW_URL="https://${DOMAIN}/"

echo "==> qr.png を再生成します（対象URL: ${NEW_URL}）..."
python3 - "${NEW_URL}" <<'PYEOF'
import sys
import segno

url = sys.argv[1]
qr = segno.make(url, error='h')
qr.save('qr.png', scale=12, border=4, dark='#1f7a5c', light='#ffffff')
PYEOF
echo "==> qr.png を更新しました。"

# ---------------------------------------------------------------------------
# 6. テストを実行し、失敗したら中断する
# ---------------------------------------------------------------------------

echo "==> npm test を実行します..."
if ! npm test; then
  echo "エラー: npm test が失敗しました。ドメイン切り替えは完了していますが、内容を確認してください。" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# 7. 完了メッセージと、レジストラで設定すべきDNSレコードの案内
# ---------------------------------------------------------------------------

cat <<EOS

==================================================================
ドメインの切り替え作業が完了しました。
新しい公開URL: ${NEW_URL}

【重要】この変更はまだコミット・プッシュされていません。
      内容を確認のうえ、ご自身で git add / commit / push してください。

------------------------------------------------------------------
◆ ドメインのレジストラ（お名前.com 等）で設定するDNSレコード
------------------------------------------------------------------

1. ルートドメイン（apex）用の A レコード（4件すべて登録）:
     185.199.108.153
     185.199.109.153
     185.199.110.153
     185.199.111.153

2. （任意）AAAA レコード（IPv6、4件すべて登録）:
     2606:50c0:8000::153
     2606:50c0:8001::153
     2606:50c0:8002::153
     2606:50c0:8003::153

3. www サブドメイン用の CNAME レコード:
     www  ->  ${GH_PAGES_HOST}

------------------------------------------------------------------
◆ DNS設定後にやること
------------------------------------------------------------------
GitHubリポジトリの Settings → Pages で、
Custom domain に "${DOMAIN}" を設定し、
"Enforce HTTPS" を有効にしてください。
証明書の発行には最大で約24時間かかる場合がありますが、
通常は数分程度で完了します。
==================================================================
EOS
